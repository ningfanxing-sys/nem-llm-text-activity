"""All scientific execution needs a later, separately authorized task receipt.
This module performs no I/O on import. The design freeze alone is never a permit.
"""
from dataclasses import dataclass
from pathlib import Path
import hashlib,json
@dataclass(frozen=True)
class ExecutionPermit:
    task_id: str
    design_freeze_sha256: str
    completed_input_manifest_sha256: str
    inputs_frozen_before_values: bool
    predictions_sealed: bool = False

def digest(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for chunk in iter(lambda:f.read(1048576),b''):h.update(chunk)
    return h.hexdigest()

def require_execution(permit, *, scoring=False):
    if not isinstance(permit,ExecutionPermit) or not permit.task_id or not permit.inputs_frozen_before_values:
        raise PermissionError('CONF is design only: a separate execution task and completed input freeze are required')
    if len(permit.design_freeze_sha256)!=64 or len(permit.completed_input_manifest_sha256)!=64:
        raise PermissionError('Missing design or completed-input freeze identity')
    if scoring and not permit.predictions_sealed:
        raise PermissionError('All registered predictions must be sealed before scoring')
    return permit

def load_permit(receipt_path, conf_dir):
    """Later task only. Its receipt cannot be generated by CONF design code."""
    root=Path(conf_dir);receipt=json.loads(Path(receipt_path).read_text())
    if receipt.get('state')!='SEPARATE_EXECUTION_TASK_AUTHORIZED':
        raise PermissionError('No separate execution authorization')
    if receipt['design_freeze_sha256']!=digest(root/'FREEZE.json'):
        raise PermissionError('Design freeze drift')
    manifest=Path(receipt['completed_input_manifest_path'])
    if receipt['completed_input_manifest_sha256']!=digest(manifest):raise PermissionError('Input manifest drift')
    inputs=json.loads(manifest.read_text())
    if inputs.get('pending_dependencies'):raise PermissionError('Inputs still incomplete')
    for item in inputs['inputs']:
        if digest(item['path'])!=item['sha256']:raise PermissionError('Input bytes drift: '+item['path'])
    for rel,item in json.loads((root/'FREEZE.json').read_text())['frozen_files'].items():
        if digest(root/rel)!=item['sha256']:raise PermissionError('Frozen code/protocol drift: '+rel)
    permit=ExecutionPermit(receipt['task_id'],receipt['design_freeze_sha256'],receipt['completed_input_manifest_sha256'],True,receipt.get('predictions_sealed',False))
    return require_execution(permit)
